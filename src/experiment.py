import csv
from pathlib import Path

from baseline_one_shot import run_baseline_trial
from tpc_basic import run_tpc_trial
from tpc_retry import run_tpc_retry_trial


def append_rows(rows, protocol_name, mobile, n_list, loss_list, seeds, vote_yes_prob=1.0, speed=0.8):
    for n in n_list:
        for loss in loss_list:
            for seed in seeds:
                if protocol_name == "ONE_SHOT":
                    row = run_baseline_trial(
                        n_participants=n,
                        loss=loss,
                        seed=seed,
                        until=80.0,
                        verbose=False,
                        mobile=mobile,
                        speed=speed if mobile else 0.0,
                    )

                elif protocol_name == "2PC":
                    row = run_tpc_trial(
                        n_participants=n,
                        loss=loss,
                        seed=seed,
                        vote_yes_prob=vote_yes_prob,
                        until=80.0,
                        verbose=False,
                        mobile=mobile,
                        speed=speed if mobile else 0.0,
                    )

                elif protocol_name == "2PC_RETRY":
                    row = run_tpc_retry_trial(
                        n_participants=n,
                        loss=loss,
                        seed=seed,
                        vote_yes_prob=vote_yes_prob,
                        until=80.0,
                        verbose=False,
                        mobile=mobile,
                        speed=speed if mobile else 0.0,
                        vote_timeout=3.0,
                        decision_timeout=3.0,
                        max_prepare_retries=2,
                        max_decision_retries=2,
                    )
                else:
                    raise ValueError(protocol_name)

                rows.append(row)


def run_all():
    out_dir = Path(__file__).resolve().parent.parent / "data"
    out_dir.mkdir(exist_ok=True)

    rows = []
    seeds = range(30)
    n_list = [3, 5, 8]
    loss_list = [0.0, 0.1, 0.2, 0.3, 0.4]

    append_rows(rows, "ONE_SHOT", mobile=False, n_list=n_list, loss_list=loss_list, seeds=seeds)
    append_rows(rows, "2PC", mobile=False, n_list=n_list, loss_list=loss_list, seeds=seeds, vote_yes_prob=1.0)
    append_rows(rows, "2PC_RETRY", mobile=False, n_list=n_list, loss_list=loss_list, seeds=seeds, vote_yes_prob=1.0)

    append_rows(rows, "ONE_SHOT", mobile=True, n_list=n_list, loss_list=loss_list, seeds=seeds)
    append_rows(rows, "2PC", mobile=True, n_list=n_list, loss_list=loss_list, seeds=seeds, vote_yes_prob=1.0)
    append_rows(rows, "2PC_RETRY", mobile=True, n_list=n_list, loss_list=loss_list, seeds=seeds, vote_yes_prob=1.0)

    keys = sorted({k for row in rows for k in row.keys()})
    with open(out_dir / "results.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Data saved to {out_dir / 'results.csv'}")

    summary = out_dir / "README_results.txt"
    with open(summary, "w") as f:
        f.write("Generated by src/experiment.py\n")
        f.write(f"rows={len(rows)}\n")
        f.write("protocols=ONE_SHOT,2PC,2PC_RETRY\n")
        f.write("scenarios=static,mobile\n")
        f.write("n_participants=3,5,8\n")
        f.write("loss=0.0,0.1,0.2,0.3,0.4\n")
        f.write("seeds=0..29\n")

    print(f"README_results.txt saved to {summary}")

if __name__ == "__main__":
    run_all()